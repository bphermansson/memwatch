"""systemd user service installation for memwatch."""

from __future__ import annotations

import logging
import shutil
import subprocess
import sys
from pathlib import Path

from . import config as config_mod

log = logging.getLogger("memwatch.service")

UNIT_NAME = "memwatch.service"

UNIT_TEMPLATE = """[Unit]
Description=memwatch memory watchdog
After=graphical-session.target
PartOf=graphical-session.target

[Service]
Type=simple
ExecStart=%h/.local/bin/memwatch run
Restart=on-failure
RestartSec=5
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=default.target
"""

LAUNCHER_TEMPLATE = """#!/bin/sh
# memwatch launcher (generated by `memwatch install`)
export PYTHONPATH="{pkg_parent}${{PYTHONPATH:+:$PYTHONPATH}}"
exec "{python}" -m memwatch "$@"
"""


def unit_dir() -> Path:
    return config_mod.xdg_config_home() / "systemd" / "user"


def unit_path() -> Path:
    return unit_dir() / UNIT_NAME


def launcher_path() -> Path:
    return Path.home() / ".local" / "bin" / "memwatch"


def _systemctl(*args: str) -> subprocess.CompletedProcess | None:
    if not shutil.which("systemctl"):
        log.error("systemctl not found; cannot manage the service")
        return None
    cmd = ["systemctl", "--user", *args]
    log.debug("running: %s", " ".join(cmd))
    return subprocess.run(cmd, check=False, text=True)


def write_launcher() -> Path:
    pkg_parent = Path(__file__).resolve().parent.parent
    target = launcher_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        LAUNCHER_TEMPLATE.format(pkg_parent=pkg_parent, python=sys.executable),
        encoding="utf-8",
    )
    target.chmod(0o755)
    log.info("wrote launcher %s", target)
    return target


def write_unit(force: bool = False) -> Path:
    target = unit_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() and not force:
        log.info("unit already exists at %s (use --force to overwrite)", target)
        return target
    target.write_text(UNIT_TEMPLATE, encoding="utf-8")
    log.info("wrote unit %s", target)
    return target


def install(force: bool = False, start: bool = True) -> int:
    config_mod.write_default_config()
    write_launcher()
    write_unit(force=force)

    result = _systemctl("daemon-reload")
    if result is None:
        return 1
    if start:
        result = _systemctl("enable", "--now", UNIT_NAME)
        if result is None or result.returncode != 0:
            log.error("failed to enable/start %s", UNIT_NAME)
            return 1
        log.info("memwatch service enabled and started")
    else:
        _systemctl("enable", UNIT_NAME)
        log.info("memwatch service enabled (not started)")
    return 0


def uninstall() -> int:
    _systemctl("disable", "--now", UNIT_NAME)
    target = unit_path()
    if target.exists():
        target.unlink()
        log.info("removed unit %s", target)
    launcher = launcher_path()
    if launcher.exists():
        launcher.unlink()
        log.info("removed launcher %s", launcher)
    _systemctl("daemon-reload")
    return 0


def status() -> int:
    if not unit_path().exists():
        print(f"memwatch service is not installed (no {unit_path()})")
        return 1
    result = _systemctl("status", "--no-pager", UNIT_NAME)
    return 0 if result is not None and result.returncode == 0 else 1
